/// What the installer prints: the lines that make jlo permanent, and the one
/// that makes it effective in the shell the user is sitting in.
///
/// The installer cannot do that second part itself - it runs in a subshell
/// under `curl | bash` and cannot mutate its parent (ADR-0001, the same reason
/// `jlo env` exists at all). That the *user* runs it is what keeps this
/// non-invasive rather than merely convenient: nothing writes to their profile
/// but them.
///
/// The text is the same whatever the user's shell and dotfiles. It names the
/// usual files and leaves the choice to the user, instead of reading `$SHELL`
/// and probing login files to print a command for one of them: a wrong guess
/// there is a file the shell never reads, or - bash - a new login file that
/// switches off the one the user relies on.
///
/// Everything here goes to stderr. stdout is the environment channel, and
/// `selfupdate` prints the reload lines there for the wrapper to eval.
fn report(layout: &Layout, reinstall: bool, symlink: Option<&Path>) {
    let home_dir = std::env::home_dir();
    let home = home_dir.as_deref();

    ui::created!("J'Lo {VERSION} installed to {}.", tilde(&layout.home, home));

    // Column 0, not indented. These lines exist to be copied, and every
    // terminal's double-click and shift-select take a leading indent with
    // them - the block a user meets on first contact was the least
    // copy-pasteable output the program produced. Structure is carried by the
    // blank line and the heading above each group instead.
    let main = snippet(layout, home, "jlo.sh");

    // A reinstall does not read the profile to decide whether the user is
    // set up: no text scan can prove a source line actually runs, and a false
    // "yes" withholds the one line that would fix a broken setup. The line is
    // printed, and the user is the one who knows.
    if reinstall {
        eprintln!(
            "\n{}",
            ui::dim("Already in your profile? Nothing to do. Otherwise add:")
        );
        eprintln!("{}", ui::command(&source_line(&main)));
    } else {
        eprintln!(
            "\n{}\n",
            ui::dim("To activate, add these lines to ~/.zshrc or ~/.bashrc:")
        );
        for name in ["jlo.sh", "autoload.sh", "completions.sh"] {
            eprintln!(
                "{}",
                ui::command(&source_line(&snippet(layout, home, name)))
            );
        }
        // The bash trap: macOS terminals start login shells, which never read
        // `.bashrc`, and read only the first login file that exists - so
        // creating `.bash_profile` beside a `.profile` switches that off.
        eprintln!(
            "\n{}",
            ui::dim(format!(
                "The last two are optional: switch JDK on cd, and tab completion.\n\
                 A login bash (what macOS terminals start) skips ~/.bashrc: there, use the\n\
                 first of {BASH_LOGIN_FILES} that exists, else ~/.bash_profile."
            ))
        );
        eprintln!("\n{}\n", ui::dim("Then load it into this shell:"));
        eprintln!("{}", ui::command(&format!(". {main}")));
        eprintln!(
            "\n{}",
            ui::dim("These lines never change: upgrades regenerate the files they point at.")
        );
    }
    path_nudge(symlink, home);
}

/// The files `bash -l` looks for, in the order it looks. It reads only the
/// first one that exists.
const BASH_LOGIN_FILES: &str = "~/.bash_profile, ~/.bash_login, ~/.profile";

/// Only nudge about PATH when the symlink was actually created and
/// `~/.local/bin` is not already on PATH - usually the case on macOS, rarely
/// on Linux. The line names its files, because the natural place to put a
/// bare `export` - beside the activation lines in `~/.zshrc` - is the one file
/// the shells it is for never read: zsh reads `~/.zshenv` for `-c` and `-lc`
/// alike, and bash has no such file at all, so a login file is the closest.
fn path_nudge(symlink: Option<&Path>, home: Option<&Path>) {
    let Some(link) = symlink else { return };
    let Some(dir) = link.parent() else { return };
    let on_path = std::env::var_os("PATH")
        .is_some_and(|path| std::env::split_paths(&path).any(|entry| entry == dir));
    if on_path {
        return;
    }
    // The prose is dim like the heading under it: in this block everything
    // except the command is scaffolding, and a paragraph louder than its own
    // heading reads as the point when it is not.
    eprintln!(
        "\n{}\n",
        ui::dim(format!(
            "'jlo' also wants {} on PATH - for non-interactive shells\n\
             (CI, scripts, AI agents) and for 'jlo home'.",
            tilde(dir, home)
        ))
    );
    eprintln!(
        "{}\n",
        ui::dim(format!(
            "Add this line to ~/.zshenv, or for bash to the first of\n\
             {BASH_LOGIN_FILES} that exists, else ~/.bash_profile:"
        ))
    );
    eprintln!("{}", ui::command(PATH_LINE));
}

/// The line the PATH hint prints. It runs in every nested shell, so it adds
/// `~/.local/bin` only once, leaves no stray colon on an empty PATH and reads
/// PATH nounset-safely. It *appends*: J'Lo only needs `jlo` to be found, and
/// prepending would change which of the user's other tools in that directory
/// win.
const PATH_LINE: &str = r#"case ":${PATH-}:" in *":$HOME/.local/bin:"*) ;; *) export PATH="${PATH:+$PATH:}$HOME/.local/bin" ;; esac"#;

// ---------------------------------------------------------------------------
// Rendering helpers
// ---------------------------------------------------------------------------

/// A default install prints the unexpanded `"$HOME/.jlo/..."` so the same line
/// works on another machine; the generated files it points at hold the real
/// paths. A custom `JLO_HOME` is quoted like any other baked path, so a `$` in
/// it stays a `$`.
fn snippet(layout: &Layout, home: Option<&Path>, name: &str) -> String {
    if home.is_some_and(|h| layout.home == h.join(crate::JLO_HOME_DIR_NAME)) {
        format!("\"$HOME/{}/{name}\"", crate::JLO_HOME_DIR_NAME)
    } else {
        sq(&display(&layout.home.join(name)))
    }
}

fn source_line(path: &str) -> String {
    format!("[ -s {path} ] && . {path}")
}

/// POSIX single-quoting, as the one implementation of it.
///
/// Every value this module writes into generated shell code goes through
/// here, for the same reason `jlo env`'s exports do: the line is executed, so
/// a `$`, a backtick or a quote in a `JLO_HOME` path is code rather than
/// data. A second copy of the rule is a second thing to get wrong, so this is
/// a rename of `shellenv::shell_quote` and nothing more.
use crate::shellenv::shell_quote as sq;

fn display(path: &Path) -> String {
    path.to_string_lossy().into_owned()
}

/// Write `contents` to `path` via a temp file **in `path`'s own directory**.
///
/// `rename` is only atomic within one filesystem, so the staging file cannot
/// live in `std::env::temp_dir()`; a sibling is the only placement that holds
/// when `bin/` is itself a mount point or a symlink. Without this an
/// interruption leaves a *truncated* script, which is worse than a stale one.
fn write_atomic(path: &Path, contents: &[u8]) -> Result<()> {
    let dir = path
        .parent()
        .ok_or_else(|| anyhow!("{path:?} has no parent directory."))?;
    let name = path
        .file_name()
        .ok_or_else(|| anyhow!("{path:?} has no file name."))?
        .to_string_lossy()
        .into_owned();
    let tmp = dir.join(format!(".{name}.tmp{}", std::process::id()));

    let staged = fs::File::create(&tmp).and_then(|mut f| {
        f.write_all(contents)?;
        f.sync_all()
    });
    if let Err(e) = staged {
        let _ = fs::remove_file(&tmp);
        return Err(anyhow!("could not write {path:?}: {e}."));
    }
    if let Err(e) = fs::rename(&tmp, path) {
        let _ = fs::remove_file(&tmp);
        return Err(anyhow!("could not write {path:?}: {e}."));
    }
    sync_dir(dir);
    Ok(())
}

/// Make a `rename` durable by flushing the *directory entry*, not just the
/// file's contents.
///
/// Without it the ordering this module relies on is not a crash guarantee at
/// all: a crash could otherwise leave the new directory entry durable in front
/// of contents still only in the page cache. Best effort, because some
/// filesystems refuse an `fsync` on a directory and that is not a reason to
/// fail an install that otherwise succeeded.
fn sync_dir(dir: &Path) {
    if let Ok(handle) = fs::File::open(dir) {
        let _ = handle.sync_all();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn layout_at(home: &Path) -> Layout {
        Layout::new(home.to_path_buf())
    }

    #[test]
    fn a_default_home_keeps_the_snippet_portable() {
        let home = Path::new("/home/u");
        let layout = layout_at(&home.join(".jlo"));
        assert_eq!(
            snippet(&layout, Some(home), "jlo.sh"),
            "\"$HOME/.jlo/jlo.sh\""
        );
    }

    #[test]
    fn a_custom_home_is_spelled_out_and_quoted() {
        let home = Path::new("/home/u");
        let layout = layout_at(Path::new("/opt/jlo"));
        assert_eq!(snippet(&layout, Some(home), "jlo.sh"), "'/opt/jlo/jlo.sh'");
    }

    #[test]
    fn write_atomic_leaves_no_temp_file_behind() {
        let dir = tempfile::tempdir().expect("tempdir");
        let path = dir.path().join("jlo.sh");
        write_atomic(&path, b"hello\n").expect("write");
        assert_eq!(fs::read_to_string(&path).expect("read"), "hello\n");
        let leftovers: Vec<_> = fs::read_dir(dir.path())
            .expect("read_dir")
            .filter_map(Result::ok)
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|n| n != "jlo.sh")
            .collect();
        assert!(
            leftovers.is_empty(),
            "temp files left behind: {leftovers:?}"
        );
    }
}
