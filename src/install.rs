/// Run the install verb. `args` is the raw argv *after* the verb token.
pub(crate) fn cmd_install(args: &[String]) -> Result<(), CommandError> {
    let layout = Layout::new(crate::jlo_home_dir()?);
    // Armed before the options are read: the installer that `exec`d us has no
    // line left to run, so a run that ends early - a rejected option included -
    // is the last chance to clear the directory we came out of. Dropping it
    // removes the directory on every path, including the successful one, where
    // the rename has already emptied it.
    let staging = Staging::around(&layout, args.iter().any(|arg| arg == "--publish-self"));
    let mut publish_self = false;
    for arg in args {
        match arg.as_str() {
            "--publish-self" => publish_self = true,
            other => return Err(anyhow!("unknown option {other:?} for {VERB}").into()),
        }
    }
    // An installer killed after unpacking leaves its staging directory, and
    // every run has a new pid, so nothing else ever comes back for it.
    layout.sweep_stale_staging(staging.dir());
    // Read before writing: a first install gets the activation block, a
    // reinstall one line.
    let reinstall = layout.home.join("jlo.sh").exists();

    if publish_self {
        // Nothing under `$JLO_HOME` has been written yet: whatever was
        // installed before is intact.
        publish_binary(&layout).map_err(|e| {
            CommandError::with_hint(
                e,
                "J'Lo was not changed; any existing install is still in place.",
            )
        })?;
    }
    let stubs_replaced = write_layout(&layout)?;
    remove_retired(&layout, stubs_replaced);
    let symlink = ensure_symlink(&layout);

    report(&layout, reinstall, symlink.as_deref());
    Ok(())
}

/// Remove what earlier releases wrote and nothing reads any more - but only a
/// file whose contents prove J'Lo wrote it: `$JLO_HOME` may be a directory the
/// user already kept other things in. The empty `.selfupdate.lock` proves
/// nothing, so it stays.
///
/// The dialect files go only once every stub has been replaced: a stub this
/// run could not rewrite is an old one, and still sources them.
///
/// A leftover that cannot be removed costs disk space, not a working install,
/// so it is a warning.
fn remove_retired(layout: &Layout, stubs_replaced: bool) {
    let mut ours = Vec::new();
    let receipt = layout.home.join(RETIRED_RECEIPT);
    if fs::read_to_string(&receipt).is_ok_and(|text| is_retired_receipt(&text)) {
        ours.push(receipt);
    }
    if stubs_replaced {
        for name in RETIRED_DIALECTS {
            let path = layout.bin.join(name);
            if fs::read_to_string(&path).is_ok_and(|text| text.starts_with(RETIRED_DIALECT_HEADER))
            {
                ours.push(path);
            }
        }
    }
    for path in ours {
        if let Err(e) = fs::remove_file(&path) {
            ui::warning!("could not remove {path:?}, which J'Lo no longer uses: {e}");
        }
    }
}

/// Whether `text` is the pretty-printed receipt 0.4.0 and 0.5.0 wrote: its
/// keys, in their order, one per line, and an optional `symlink` last.
fn is_retired_receipt(text: &str) -> bool {
    let mut lines = text.lines();
    if lines.next() != Some("{") {
        return false;
    }
    for key in ["version", "method", "jlo_home", "binary"] {
        if !lines
            .next()
            .is_some_and(|line| line.starts_with(&format!("  \"{key}\": \"")))
        {
            return false;
        }
    }
    let mut rest = lines.next();
    if rest.is_some_and(|line| line.starts_with("  \"symlink\": \"")) {
        rest = lines.next();
    }
    rest == Some("}") && lines.next().is_none()
}

/// Move the running executable to its published path.
///
/// The installers unpack into a staging directory *beside* the destination
/// and run the staged binary from there, so that this - the write that
/// replaces `bin/jlo-bin` - happens only once the new binary has proved it can
/// start. An installer that wrote the binary itself would, on Linux, hit
/// `ETXTBSY` trying to overwrite a binary that is still running.
///
/// Beside the destination, and not under `$TMPDIR`, because `rename` is atomic
/// only within one filesystem and fails outright across two.
///
/// On Unix the process keeps its inode across the rename, so from here on this
/// process *is* the published binary - which is what makes it safe for the
/// same run to go on and write the layout from its own `include_str!`
/// templates. There is no second `exec`.
///
/// A binary already at the published path - `install-local.sh`, a re-run -
/// is left alone rather than renamed onto itself.
fn publish_binary(layout: &Layout) -> Result<()> {
    let exe = std::env::current_exe().context("could not find the running J'Lo binary")?;
    let target = layout.binary();
    if same_path(&exe, &target) {
        return Ok(());
    }

    fs::create_dir_all(layout.bin_dir())
        .with_context(|| format!("could not create {:?}", layout.bin_dir()))?;
    // The staged file's *contents* first. The installers wrote it with `tar`
    // or `cp`, and neither flushed it, so a crash just after the rename could
    // leave a durable directory entry - and the layout written next vouching
    // for it - in front of a binary that is still only in the page cache.
    // `sync_dir` below flushes the entry, not the data behind it.
    File::open(&exe)
        .and_then(|handle| handle.sync_all())
        .with_context(|| format!("could not flush {exe:?} to disk"))?;
    fs::rename(&exe, &target)
        .with_context(|| format!("could not publish {exe:?} to {target:?}"))?;
    // The rename is only durable once the directory entry is, and the layout
    // written next is generated by the binary published here.
    sync_dir(layout.bin_dir());

    Ok(())
}

pub(crate) fn is_current_exe(path: &Path) -> bool {
    let Ok(exe) = std::env::current_exe() else {
        return false;
    };
    same_path(&exe, path)
}

/// The installer's staging directory, swept when this value is dropped.
///
/// `install.sh` and `install-local.sh` unpack into `bin/.jlo-install-<pid>/`
/// and run the binary from there. `install.sh` `exec`s it, so from that moment
/// the staged process is the only one that can still tidy up: a refused
/// publish would otherwise leave a whole copy of J'Lo in `bin/` for every
/// failed install.
///
/// What it removes is the file it knows was staged, and then the directory
/// *only if that emptied it*. Never a recursive delete: this runs on a path
/// derived from `current_exe()`, and a wrong answer there must cost nothing
/// that belongs to somebody else.
#[derive(Debug)]
struct Staging(Option<PathBuf>);

impl Staging {
    /// `None` unless this executable is demonstrably a staged one.
    ///
    /// Three things have to hold, and the name is the weakest of them: the
    /// caller must have asked to publish, the executable must not already be
    /// the published binary - `install-local.sh`, a re-run - and the
    /// directory it sits in must be a child of *this* install's `bin/`.
    /// Without that last test a binary parked in any directory whose name
    /// happens to start with `.jlo-install` would be swept while the verb was
    /// pointed at an unrelated `$JLO_HOME`.
    fn around(layout: &Layout, publish_self: bool) -> Self {
        if !publish_self {
            return Self(None);
        }
        let Ok(exe) = std::env::current_exe() else {
            return Self(None);
        };
        if same_path(&exe, &layout.binary()) {
            return Self(None);
        }
        let dir = exe.parent().filter(|dir| {
            dir.file_name()
                .is_some_and(|name| name.to_string_lossy().starts_with(STAGING_PREFIX))
                && dir
                    .parent()
                    .is_some_and(|up| same_path(up, layout.bin_dir()))
        });
        Self(dir.map(Path::to_path_buf))
    }

    fn dir(&self) -> Option<&Path> {
        self.0.as_deref()
    }
}

impl Drop for Staging {
    fn drop(&mut self) {
        let Some(dir) = self.0.take() else {
            return;
        };
        // Gone already on the happy path: publishing renamed it out.
        let _ = fs::remove_file(dir.join(BINARY_NAME));
        // Not `remove_dir_all`. Anything still in here was not put there by
        // this run, and keeping it costs an empty directory at worst.
        let _ = fs::remove_dir(&dir);
    }
}

/// The one thing this verb writes to **stdout** (ADR-0001): shell code for the
/// caller to `eval`, which is how the shell that ran `jlo selfupdate` gets the
/// freshly generated wrapper in place of its resident one.
///
/// Only `selfupdate` prints it. The install verb does not: `install.sh`'s
/// stdout is not evaluated by anything, and the line would be noise there -
/// the activation block `report` prints is what a bootstrap needs.
///
/// The two optional lines re-source only what this shell had *already*
/// enabled, never more. The signal is the marker each stub sets after it
/// successfully loads: a plain (unexported) shell variable, which is exactly
/// the state the wrapper left behind in this shell and nothing a child process
/// or another session can fake into existence here.
///
/// Every optional line is a full `if`, not `[ ... ] && . ...`: a
/// `[ -n ... ]` that is simply false would fail the `&&`-joined payload and
/// turn a successful update into a non-zero `jlo selfupdate`.
pub(crate) fn print_reload(layout: &Layout, wrapped: bool) -> Result<()> {
    let jlo_sh = sq(&display(&layout.home.join("jlo.sh")));
    let autoload = sq(&display(&layout.home.join("autoload.sh")));
    let completions = sq(&display(&layout.home.join("completions.sh")));
    crate::shellenv::emit(
        &[
            format!(". {jlo_sh}"),
            format!("if [ -n \"${{{AUTOLOAD_MARKER}-}}\" ]; then . {autoload}; fi"),
            format!("if [ -n \"${{{COMPLETIONS_MARKER}-}}\" ]; then . {completions}; fi"),
        ],
        wrapped,
    )
}

/// Everything under `$JLO_HOME` except the binary and the symlink.
///
/// Shared with `jlo selfupdate`'s repair, through [`refresh_layout`]. The two
/// optional stubs and the completion scripts warn rather than fail: a
/// convenience lost is not a broken install, and the user gets a warning
/// naming the file and the repair.
///
/// Answers whether every stub was replaced; an optional one that was not may
/// still be an earlier release's.
fn write_layout(layout: &Layout) -> Result<bool> {
    fs::create_dir_all(&layout.bin)
        .with_context(|| format!("could not create {:?}", layout.bin))?;

    // The wrappers first: the stubs below are what point at them.
    for (name, body) in [
        ("jlo-init.sh", INIT),
        ("jlo-autoload.sh", AUTOLOAD),
        ("jlo-completions.zsh", COMPLETIONS_ZSH),
    ] {
        write_atomic(&layout.bin.join(name), body.as_bytes())?;
    }

    let completions_partial = write_completions(layout);
    let mut stubs_replaced = true;

    // The one file a user cannot skip: it defines the wrapper function and
    // exports the JLO_HOME the rest of the layout hangs off. A failure here
    // means the printed instructions would point at nothing, so it is fatal
    // where the two optional stubs are warnings.
    let jlo_sh = init_stub(
        layout,
        "\
# Source this from your shell profile. The line never changes: an upgrade
# regenerates the files it points at.
",
    );
    write_atomic(&layout.home.join("jlo.sh"), jlo_sh.as_bytes())
        .context("could not write jlo.sh; J'Lo cannot be loaded from your shell profile.")?;

    let autoload_sh = autoload_stub(
        layout,
        "\
# Optional: switches JDK on cd when a .jlorc is in scope. Source after jlo.sh.
",
    );
    if let Err(e) = write_atomic(&layout.home.join("autoload.sh"), autoload_sh.as_bytes()) {
        ui::warning!("{e:#} cd autoloading is unavailable.");
        stubs_replaced = false;
    }
    if let Err(e) = write_atomic(
        &layout.home.join("completions.sh"),
        completions_sh(layout).as_bytes(),
    ) {
        ui::warning!("{e:#} Tab completion is unavailable.");
        stubs_replaced = false;
    }
    // One recovery line for every optional file that did not land, however
    // many of them failed.
    if completions_partial || !stubs_replaced {
        ui::hint!("Re-run the installer once that path is writable to restore it.");
    }
    Ok(stubs_replaced)
}

/// Everything under `$JLO_HOME` but the binary: the generated files and the
/// `~/.local/bin/jlo` link, by the same rules the install verb follows.
///
/// What `jlo selfupdate` does when J'Lo is already current - the repair for an
/// upgrade cut off between the binary and its scripts. Only a required file
/// that cannot be written is an error.
pub(crate) fn refresh_layout(layout: &Layout) -> Result<()> {
    write_layout(layout)?;
    ensure_symlink(layout);
    Ok(())
}

/// Completion scripts, generated from this binary's own clap tree.
///
/// Written at install time rather than loaded via `source <(jlo completions
/// bash)` so that shell startup costs no subprocess. A failure is a
/// convenience lost, not a broken install: it is warned about here, and
/// reported as `true` so the caller prints the one repair hint for every
/// optional file that did not land.
fn write_completions(layout: &Layout) -> bool {
    if let Err(e) = fs::create_dir_all(&layout.completions) {
        ui::warning!(
            "could not create {:?}: {e}. Shell completions are unavailable.",
            layout.completions
        );
        return true;
    }
    let mut partial = false;
    for (shell, name) in [
        (clap_complete::Shell::Bash, "jlo.bash"),
        (clap_complete::Shell::Zsh, "_jlo"),
    ] {
        let script = crate::cli::completion_script(shell);
        if let Err(e) = write_atomic(&layout.completions.join(name), &script) {
            ui::warning!("{e:#} {shell} completions are unavailable.");
            partial = true;
        }
    }
    partial
}

